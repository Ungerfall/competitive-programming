public class Solution
{
    private static readonly (int dRow, int dCol)[] Directions = [
        (-1, 0),
        (0, 1),
        (1, 0),
        (0, -1)
    ];
    public int[][] UpdateMatrix(int[][] mat)
    {
        if (mat.Length == 0)
        {
            return Array.Empty<int[]>();
        }

        int[][] dist = new int[mat.Length][];
        for (int i = 0; i < dist.Length; i++)
        {
            dist[i] = new int[mat[0].Length];
            Array.Fill(dist[i], int.MaxValue);
        }

        int rows = mat.Length;
        int cols = mat[0].Length;
        for (int row = 0; row < rows; row++)
        {
            for (int col = 0; col < cols; col++)
            {
                if (mat[row][col] != 0)
                {
                    distToNearestZero(row, col);
                }
                else
                {
                    dist[row][col] = 0;
                }
            }
        }

        return dist;

        void distToNearestZero(int row, int col)
        {
            bool[,] seen = new bool[rows, cols];
            Queue<(int row, int col)> toVisit = [];
            toVisit.Enqueue((row, col));
            int level = 0;
            while (toVisit.Count > 0)
            {
                for (int onLevel = toVisit.Count; onLevel > 0; onLevel--)
                {
                    (int currentRow, int currentCol) = toVisit.Dequeue();
                    seen[currentRow, currentCol] = true;
                    if (mat[currentRow][currentCol] == 0)
                    {
                        dist[row][col] = Math.Min(dist[row][col], level);
                        return;
                    }

                    if (level >= dist[row][col])
                    {
                        continue;
                    }

                    if (dist[currentRow][currentCol] != int.MaxValue)
                    {
                        dist[row][col] = Math.Min(dist[row][col], level + dist[currentRow][currentCol]);
                        continue;
                    }

                    foreach ((int dRow, int dCol) in Directions)
                    {
                        int newRow = currentRow + dRow;
                        int newCol = currentCol + dCol;
                        if (newRow < 0 || newRow >= rows || newCol < 0 || newCol >= cols)
                        {
                            continue;
                        }

                        if (seen[newRow, newCol])
                        {
                            continue;
                        }

                        toVisit.Enqueue((newRow, newCol));
                    }
                }

                level++;
            }
        }
    }
}
